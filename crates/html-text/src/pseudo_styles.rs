//! First-line and first-letter style selection.

use crate::first_letter::first_letter_range;
use crate::normalization::whitespace_context_root;
use crate::{InlineContent, InlineItemKind, TextStructure};
use html_dom::{Document, DomNodeId, MemoryUsageReport};
use html_style_model::{ComputedStyles, StyleIndices};
use rustc_data_structures::fx::{FxHashMap, FxHashSet};

/// Pseudo-style ownership resolved once in logical source order.
#[derive(Clone, Default)]
pub struct PseudoStyles {
    roots: FxHashMap<usize, RootPseudoStyles>,
}

#[derive(Clone, Default)]
struct RootPseudoStyles {
    first_line: Option<StyleIndices>,
    first_letter: Option<(DomNodeId, StyleIndices)>,
}

impl PseudoStyles {
    pub(crate) fn new(
        document: &Document,
        styles: &ComputedStyles,
        tree: &(impl TextStructure + ?Sized),
        content: &InlineContent,
    ) -> Self {
        let mut result = Self::default();
        if !styles.has_first_line_styles() && !styles.has_first_letter_styles() {
            return result;
        }
        // A preserved whitespace-only flow has no first letter to consume.
        let letter_content_roots: FxHashSet<_> = if styles.has_first_letter_styles() {
            content
                .inline_items()
                .iter()
                .filter_map(|item| {
                    let InlineItemKind::Text { glyphs } = &item.kind else {
                        return None;
                    };
                    content.characters()[glyphs.start as usize..glyphs.end as usize]
                        .iter()
                        .any(|character| !character.is_whitespace())
                        .then(|| item.flow_root(tree))
                })
                .collect()
        } else {
            FxHashSet::default()
        };
        let mut line_roots = FxHashSet::default();
        let mut letter_roots = FxHashSet::default();
        let mut line_owners = FxHashSet::default();
        let mut letter_owners = FxHashSet::default();
        for item in content.inline_items() {
            let Some(_) = item.text_run().filter(|run| !run.glyphs.is_empty()) else {
                continue;
            };
            let root = item.flow_root(tree);
            if styles.has_first_line_styles() && line_roots.insert(root) {
                if let Some((owner, style, eligible)) =
                    pseudo_style_owner(document, styles, tree, root, PseudoStyleKind::FirstLine)
                {
                    if line_owners.insert(owner.raw()) && eligible {
                        result.roots.entry(root).or_default().first_line = Some(style);
                    }
                }
            }
            if styles.has_first_letter_styles()
                && matches!(item.kind, InlineItemKind::Text { .. })
                && letter_content_roots.contains(&root)
                && letter_roots.insert(root)
            {
                consume_blocked_first_letter_owners(
                    document,
                    styles,
                    tree,
                    root,
                    &mut letter_owners,
                );
                if let Some((owner, style, eligible)) =
                    pseudo_style_owner(document, styles, tree, root, PseudoStyleKind::FirstLetter)
                {
                    if letter_owners.insert(owner.raw()) && eligible {
                        result.roots.entry(root).or_default().first_letter = Some((owner, style));
                    }
                }
            }
        }
        result
    }

    pub fn first_line(&self, root: usize) -> Option<StyleIndices> {
        self.roots.get(&root)?.first_line
    }

    pub fn first_letter(&self, root: usize) -> Option<StyleIndices> {
        self.roots.get(&root)?.first_letter.map(|(_, style)| style)
    }

    pub(crate) fn memory_usage_report(&self) -> MemoryUsageReport {
        let mut report = MemoryUsageReport::new();
        report.add(
            "InlineContent.pseudo_styles",
            self.roots.capacity() * std::mem::size_of::<(usize, RootPseudoStyles)>(),
            self.roots.len(),
        );
        report
    }
}

/// Resolve the characters generated by `::first-letter` before shaping. CSS2
/// includes adjacent Ps/Pe/Pi/Pf/Po punctuation in the pseudo-element; doing
/// this here lets the backend shape, size, and paint the whole typographic
/// unit with the pseudo style instead of trying to resize already-shaped
/// glyphs during line layout.
#[cfg(any(test, feature = "testing"))]
pub fn first_letter_style_overrides(
    document: &Document,
    styles: &ComputedStyles,
    layout_tree: &(impl TextStructure + ?Sized),
    inline_content: &InlineContent,
) -> Vec<Option<StyleIndices>> {
    first_letter_overrides_with_characters(document, styles, layout_tree, inline_content, |index| {
        inline_content.character_at(index as usize).unwrap_or('?')
    })
}

#[cfg(any(test, feature = "testing"))]
pub fn first_letter_overrides_with_characters(
    document: &Document,
    styles: &ComputedStyles,
    layout_tree: &(impl TextStructure + ?Sized),
    inline_content: &InlineContent,
    character_at: impl Fn(u32) -> char,
) -> Vec<Option<StyleIndices>> {
    let pseudos = PseudoStyles::new(document, styles, layout_tree, inline_content);
    prepare_first_letters(styles, layout_tree, inline_content, &pseudos, character_at)
}

pub(crate) fn prepare_first_letters(
    styles: &ComputedStyles,
    layout_tree: &(impl TextStructure + ?Sized),
    inline_content: &InlineContent,
    pseudos: &PseudoStyles,
    character_at: impl Fn(u32) -> char,
) -> Vec<Option<StyleIndices>> {
    // An empty override vector denotes the absence of first-letter styles.
    if !styles.has_first_letter_styles() {
        return Vec::new();
    }
    // Preserve source order. An ancestor's `::first-letter` belongs to the
    // first in-flow descendant that contributes text, not to every descendant
    // formatting context carrying that ancestor in its box chain.
    let mut root_indices = FxHashMap::<usize, usize>::default();
    let mut content_by_root = Vec::<(usize, Vec<(u32, char, usize)>)>::new();
    for run in inline_content.inline_items() {
        let InlineItemKind::Text { glyphs } = &run.kind else {
            continue;
        };
        let root = whitespace_context_root(layout_tree, run.box_idx as usize);
        let entry = if let Some(&entry) = root_indices.get(&root) {
            entry
        } else {
            let entry = content_by_root.len();
            content_by_root.push((root, Vec::new()));
            root_indices.insert(root, entry);
            entry
        };
        content_by_root[entry]
            .1
            .extend(glyphs.clone().map(|glyph_idx| {
                let character = character_at(glyph_idx);
                (glyph_idx, character, run.box_idx as usize)
            }));
    }

    let mut overrides = vec![None; inline_content.characters().len()];
    for (root, content) in content_by_root {
        let selection = first_letter_range(content.iter().map(|&(_, character, _)| character));
        if selection.is_empty() {
            continue;
        }
        let Some((owner, pseudo_style)) = pseudos
            .roots
            .get(&root)
            .and_then(|styles| styles.first_letter)
        else {
            continue;
        };

        let before_style = styles
            .before_style_for_node(owner)
            .map(|(style, _, _)| style);
        let generated_style = styles.before_first_letter_style_for_node(owner);
        for &(glyph_idx, _, box_idx) in &content[selection] {
            let comes_from_before = before_style
                .is_some_and(|style| layout_tree.get_box_style_indices(box_idx) == Some(style));
            overrides[glyph_idx as usize] = Some(if comes_from_before {
                generated_style.unwrap_or(pseudo_style)
            } else {
                pseudo_style
            });
        }
    }
    overrides
}

/// A flex or grid container does not expose a first formatted letter from its
/// items to its own (or an ancestor's) `::first-letter`. Those blocked owners
/// still have to be consumed in source order: otherwise an ancestor pseudo
/// incorrectly skips the container and styles text in a later sibling.
fn consume_blocked_first_letter_owners(
    document: &Document,
    styles: &ComputedStyles,
    layout_tree: &(impl TextStructure + ?Sized),
    mut root: usize,
    consumed_owners: &mut FxHashSet<u32>,
) {
    let mut crossed_flex_or_grid = false;
    loop {
        if crossed_flex_or_grid {
            if let Some(node) = layout_tree
                .get_box_dom_element(root)
                .and_then(|raw| document.node_id_from_raw(raw))
            {
                if styles.first_letter_style_for_node(node).is_some() {
                    consumed_owners.insert(node.raw());
                }
            }
        }

        let Some(parent) = layout_tree.get_box_parent(root) else {
            break;
        };
        if layout_tree.is_flex_or_grid(parent) {
            crossed_flex_or_grid = true;
        }
        root = parent;
    }
}

#[derive(Clone, Copy)]
enum PseudoStyleKind {
    FirstLine,
    FirstLetter,
}

/// Find the nearest originating element whose pseudo-element can apply to an
/// inline formatting context. Walking layout ancestry is essential because
/// CSS defines the first formatted line/letter through in-flow block
/// descendants, not only through text directly owned by the styled element.
fn pseudo_style_owner(
    document: &Document,
    styles: &ComputedStyles,
    layout_tree: &(impl TextStructure + ?Sized),
    mut root: usize,
    kind: PseudoStyleKind,
) -> Option<(DomNodeId, StyleIndices, bool)> {
    let mut eligible = true;
    loop {
        if let Some(node) = layout_tree
            .get_box_dom_element(root)
            .and_then(|raw| document.node_id_from_raw(raw))
        {
            let style = match kind {
                PseudoStyleKind::FirstLine => styles.first_line_style_for_node(node),
                PseudoStyleKind::FirstLetter => styles.first_letter_style_for_node(node),
            };
            if let Some(style) = style {
                return Some((node, style, eligible));
            }
        }
        let parent = layout_tree.get_box_parent(root)?;
        // Pseudos on an item itself remain eligible, but crossing into its
        // flex/grid container blocks pseudos found on that container or any
        // ancestor. Keep searching so the blocked owner is still consumed in
        // source order instead of incorrectly applying to a later sibling.
        if layout_tree.is_flex_or_grid(parent) {
            eligible = false;
        }
        root = parent;
    }
}
